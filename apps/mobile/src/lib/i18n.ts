/** Translate one Thai text for the current language (unknown → unchanged). */
export function t(text: string): string {
  if (lang === 'th' || !text || !/[฀-๿]/.test(text)) return text;
  const direct = EN[text];
  if (direct !== undefined) return direct;
  // keep outer spaces ("แบตเตอรี่ | " → "Battery | ")
  const m = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (m && (m[1] || m[3])) {
    const inner = EN[m[2]];
    if (inner !== undefined) return m[1] + inner + m[3];
  }
  for (const [re, out] of PATTERNS) {
    if (re.test(text)) return text.replace(re, out);
  }
  // last resort: word by word ("😊 ดี" → "😊 Good"); unknown words stay as they are
  if (text.includes(' ')) {
    const words = text.split(' ').map((w) => EN[w] ?? w);
    return words.join(' ');
  }
  return text;
}
